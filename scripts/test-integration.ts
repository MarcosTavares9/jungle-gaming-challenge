import { DeleteQueueCommand } from "@aws-sdk/client-sqs";
import { openDatabase, Sql } from "../src/infrastructure/database";
import { config } from "../src/infrastructure/config";

const url = new URL(config.DATABASE_URL);
const localHosts = new Set([
  "localhost",
  "127.0.0.1",
  "[::1]",
  "postgres",
  "localstack",
]);
if (
  !localHosts.has(url.hostname) ||
  !localHosts.has(new URL(config.SQS_ENDPOINT).hostname)
) {
  throw new Error(
    "A suíte de integração aceita somente PostgreSQL e SQS locais",
  );
}
const infrastructure = Bun.spawn(
  ["docker", "compose", "up", "-d", "--wait", "postgres", "localstack"],
  { stdout: "inherit", stderr: "inherit" },
);
if ((await infrastructure.exited) !== 0)
  throw new Error("Não foi possível iniciar a infraestrutura de testes");

const suffix = crypto.randomUUID().replaceAll("-", "");
const databaseName = `jungle_test_${suffix}`;
const prefix = `test-${suffix.slice(0, 12)}-`;
const testArguments = Bun.argv.slice(2);
const root = await openDatabase();
url.pathname = `/${databaseName}`;
let child: ReturnType<typeof Bun.spawn> | undefined;
let created = false;
try {
  if (!/^jungle_test_[a-f0-9]{32}$/.test(databaseName))
    throw new Error("Nome de banco inseguro");
  await new Sql(root.em.fork()).query(`CREATE DATABASE ${databaseName}`);
  created = true;
  console.log(`Integração isolada: ${databaseName}, filas ${prefix}*`);
  child = Bun.spawn(
    [
      process.execPath,
      "test",
      "tests/integration",
      "--timeout",
      "60000",
      ...testArguments,
    ],
    {
      env: {
        ...process.env,
        DATABASE_URL: url.toString(),
        SQS_QUEUE_PREFIX: prefix,
        INTEGRATION_TEST_RUN: "true",
      },
      stdout: "inherit",
      stderr: "inherit",
    },
  );
  process.exitCode = await child.exited;
} finally {
  if (child && child.exitCode === null) {
    child.kill();
    await child.exited;
  }
  // Only resources generated by this invocation are removed. The application database is untouched.
  const { SQSClient, GetQueueUrlCommand } = await import("@aws-sdk/client-sqs");
  const client = new SQSClient({
    endpoint: config.SQS_ENDPOINT,
    region: config.AWS_REGION,
    credentials: {
      accessKeyId: config.AWS_ACCESS_KEY_ID,
      secretAccessKey: config.AWS_SECRET_ACCESS_KEY,
    },
  });
  try {
    for (const name of [
      "wager-transactions.fifo",
      "wager-transactions-dlq.fifo",
      "wager-events.fifo",
    ]) {
      try {
        const queue = await client.send(
          new GetQueueUrlCommand({ QueueName: prefix + name }),
        );
        await client.send(new DeleteQueueCommand({ QueueUrl: queue.QueueUrl }));
      } catch (error) {
        if ((error as Error).name !== "QueueDoesNotExist") {
          console.error(
            "Falha na limpeza da fila",
            prefix + name,
            (error as Error).name,
          );
          process.exitCode = 1;
        }
      }
    }
    if (created)
      await new Sql(root.em.fork()).query(
        `DROP DATABASE ${databaseName} WITH (FORCE)`,
      );
  } finally {
    client.destroy();
    await root.close(true);
  }
}
